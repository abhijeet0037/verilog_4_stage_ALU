
module pipeline_test;

    // Inputs
    reg [3:0] rs1, rs2, rd, func;
    reg [7:0] addr;
    reg clk1, clk2;

    // Output
    wire [15:0] Zout;

    // Instantiate DUT
    pipe_line DUT (
        .Zout(Zout),
        .rs1(rs1),
        .rs2(rs2),
        .rd(rd),
        .func(func),
        .addr(addr),
        .clk1(clk1),
        .clk2(clk2)
    );

    //---------------------------------------------------------
    // Clock Generation
    //---------------------------------------------------------

    initial begin
        clk1 = 0;
        forever #10 clk1 = ~clk1;
    end

    initial begin
        clk2 = 0;
        #5;
        forever #10 clk2 = ~clk2;
    end

    //---------------------------------------------------------
    // Initialize Register Bank
    //---------------------------------------------------------

    integer i;

    initial begin

        for(i=0;i<16;i=i+1)
            DUT.regbank[i] = 0;

        DUT.regbank[0] = 16'd10;
        DUT.regbank[1] = 16'd20;
        DUT.regbank[2] = 16'd5;
        DUT.regbank[3] = 16'd4;
        DUT.regbank[4] = 16'd15;
        DUT.regbank[5] = 16'd8;

    end

    //---------------------------------------------------------
    // Apply Instructions
    //---------------------------------------------------------

    initial begin

        rs1 = 0;
        rs2 = 0;
        rd  = 0;
        func = 0;
        addr = 0;

        #20;

        //-------------------------------------------------
        // R6 = R0 + R1 = 10 + 20 = 30
        //-------------------------------------------------
        rs1 = 0;
        rs2 = 1;
        rd  = 6;
        func = 0;
        addr = 8'h10;

        #20;

        //-------------------------------------------------
        // R7 = R1 - R2 = 20 - 5 = 15
        //-------------------------------------------------
        rs1 = 1;
        rs2 = 2;
        rd  = 7;
        func = 1;
        addr = 8'h11;

        #20;

        //-------------------------------------------------
        // R8 = R2 * R3 = 5 * 4 = 20
        //-------------------------------------------------
        rs1 = 2;
        rs2 = 3;
        rd  = 8;
        func = 2;
        addr = 8'h12;

        #20;

        //-------------------------------------------------
        // R9 = R4 AND R5 = 15 & 8 = 8
        //-------------------------------------------------
        rs1 = 4;
        rs2 = 5;
        rd  = 9;
        func = 5;
        addr = 8'h13;

        #20;

        //-------------------------------------------------
        // R10 = R4 OR R5 = 15 | 8 = 15
        //-------------------------------------------------
        rs1 = 4;
        rs2 = 5;
        rd  = 10;
        func = 6;
        addr = 8'h14;

        #20;

        //-------------------------------------------------
        // R11 = R4 XOR R5 = 15 ^ 8 = 7
        //-------------------------------------------------
        rs1 = 4;
        rs2 = 5;
        rd  = 11;
        func = 7;
        addr = 8'h15;

        #20;

        //-------------------------------------------------
        // R12 = -R2 = -5
        //-------------------------------------------------
        rs1 = 2;
        rs2 = 0;
        rd  = 12;
        func = 8;
        addr = 8'h16;

        #20;

        //-------------------------------------------------
        // R13 = R4 >> 1 = 15 >> 1 = 7
        //-------------------------------------------------
        rs1 = 4;
        rs2 = 0;
        rd  = 13;
        func = 10;
        addr = 8'h17;

        #20;

        //-------------------------------------------------
        // R14 = R2 << 1 = 5 << 1 = 10
        //-------------------------------------------------
        rs1 = 2;
        rs2 = 0;
        rd  = 14;
        func = 11;
        addr = 8'h18;

        #100;

        $finish;

    end

    //---------------------------------------------------------
    // Monitor
    //---------------------------------------------------------

    initial begin

        $dumpfile("pipeline.vcd");
        $dumpvars(0,pipeline_test);

        $display("------------------------------------------------------------");
        $display("Time\tFunc\tRS1\tRS2\tRD\tZout");
        $display("------------------------------------------------------------");

        $monitor("%0t\t%d\t%d\t%d\t%d\t%d",
                 $time, func, rs1, rs2, rd, Zout);

    end

endmodule
